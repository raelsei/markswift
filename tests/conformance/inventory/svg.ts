/**
 * SVG domain: the 63 SVG 2 elements, the 41 Chrome computed-style properties
 * that are SVG presentation properties, and the two legacy presentation
 * attributes Chrome never exposes as properties.
 *
 * Decision already made: one `Shape` struct per unique (d, viewBox) in
 * <View>+Shapes.swift, nested in the view type (`shapeName` in src/swift/svg.ts), fill and stroke as
 * separate ZStack layers. SF Symbol substitution is NOT done by the tool: it
 * is the agent's/user's call after generation (noted on `svg:svg`).
 *
 * Today's pipeline (`buildSvg`, src/analysis/svg/build.ts): walks
 * `svg`/`g` recursively, converts `path circle rect line polyline polygon
 * ellipse` to path data, merges presentation attributes down the tree,
 * reads `fill`/`stroke`/`stroke-width`/`stroke-linecap`/`stroke-linejoin`
 * from computed style with the attribute as fallback, collapses
 * `linearGradient`/`radialGradient` to their first `stop-color`, turns a
 * `circle` with `stroke-dasharray` into a trimmed `Circle`, and only NOTES a
 * `transform` attribute. Every other element is skipped silently.
 */

