/**
 * Compiles the Tailwind v4 fixture sources (`fixtures/_tailwind-v4/*.html` → `fixtures/tailwind-v4/`, the component
 * corpus `fixtures/_components/*.html` → `fixtures/components/`, and `fixtures/_breakpoints/*.html` →
 * `fixtures/breakpoints/`) into self-contained fixtures with the CSS inlined, so
 * tests never need Tailwind or a CDN. Marker `<!-- tailwind-v4 -->` compiles against `@import "tailwindcss";`;
 * `<!-- tailwind-v4 globals.css -->` compiles against the source dir's `globals.css` (its own Tailwind entry).
 * `MARKSWIFT_TAILWIND_MODULES` = a node_modules with `tailwindcss` 4.1.x and `@tailwindcss/cli`
 * (default: the shadcn research corpus). Run: `bun tests/conformance/tailwind-v4.ts`.
 */
import { mkdtemp, rm, symlink, readdir, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const FIXTURES = join(import.meta.dir, "fixtures");
const DIRS = [
  ["_tailwind-v4", "tailwind-v4"],
  ["_components", "components"],
  ["_breakpoints", "breakpoints"],
] as const;
const MARKER = /<!-- tailwind-v4( globals\.css)? -->/;
const modules = resolve(
  process.env.MARKSWIFT_TAILWIND_MODULES ?? join(import.meta.dir, "../../research/corpora/shadcn/node_modules"),
);
const cli = join(modules, ".bin/tailwindcss");
if (!existsSync(cli))
  throw new Error(
    `${cli} not found; set MARKSWIFT_TAILWIND_MODULES to a node_modules with tailwindcss 4.1.x and @tailwindcss/cli`,
  );
const { version } = (await Bun.file(join(modules, "tailwindcss/package.json")).json()) as { version: string };
if (!version.startsWith("4.1."))
  throw new Error(`tailwindcss ${version} in ${modules}; the fixtures are pinned to 4.1.x`);

for (const [sourceDir, outDir] of DIRS) {
  const SOURCES = join(FIXTURES, sourceDir);
  const OUT = join(FIXTURES, outDir);
  await mkdir(OUT, { recursive: true });
  for (const name of (await readdir(SOURCES)).filter((f) => f.endsWith(".html")).sort()) {
    const source = join(SOURCES, name);
    const html = await Bun.file(source).text();
    const marker = html.match(MARKER);
    if (!marker) throw new Error(`${source} has no <!-- tailwind-v4 --> marker`);
    const prelude = marker[1] ? await Bun.file(join(SOURCES, "globals.css")).text() : '@import "tailwindcss";\n';
    const dir = await mkdtemp(join(tmpdir(), "markswift-tailwind-"));
    try {
      // Tailwind resolves `@import "tailwindcss"` relative to the input file.
      await symlink(modules, join(dir, "node_modules"), "dir");
      await Bun.write(join(dir, "input.css"), `${prelude}@source "${source}";\n`);
      const run = Bun.spawn([cli, "-i", "input.css", "-o", "out.css"], { cwd: dir, stdout: "pipe", stderr: "pipe" });
      const [code, stderr] = await Promise.all([run.exited, new Response(run.stderr).text()]);
      if (code !== 0) throw new Error(`tailwindcss failed for ${name} (exit ${code}):\n${stderr}`);
      const css = await Bun.file(join(dir, "out.css")).text();
      const style = `<style>\n/* Generated by tests/conformance/tailwind-v4.ts from fixtures/${sourceDir}/${name} with tailwindcss ${version}. Do not edit; regenerate. */\n${css}</style>`;
      const out = join(OUT, name);
      await Bun.write(
        out,
        html.replace(MARKER, () => style),
      );
      console.log(out);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }
}
