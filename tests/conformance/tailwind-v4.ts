/**
 * Compiles the Tailwind v4 fixture sources (`fixtures/_tailwind-v4/*.html`) into self-contained
 * fixtures (`fixtures/tailwind-v4/*.html`) with the CSS inlined, so tests never need Tailwind or a CDN.
 * `MARKSWIFT_TAILWIND_MODULES` = a node_modules with `tailwindcss` 4.1.x and `@tailwindcss/cli`
 * (default: the shadcn research corpus). Run: `bun tests/conformance/tailwind-v4.ts`.
 */
import { mkdtemp, rm, symlink, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const SOURCES = join(import.meta.dir, "fixtures/_tailwind-v4");
const OUT = join(import.meta.dir, "fixtures/tailwind-v4");
const MARKER = "<!-- tailwind-v4 -->";
const modules = resolve(process.env.MARKSWIFT_TAILWIND_MODULES ?? join(import.meta.dir, "../../research/corpora/shadcn/node_modules"));
const cli = join(modules, ".bin/tailwindcss");
if (!existsSync(cli)) throw new Error(`${cli} not found; set MARKSWIFT_TAILWIND_MODULES to a node_modules with tailwindcss 4.1.x and @tailwindcss/cli`);
const { version } = await Bun.file(join(modules, "tailwindcss/package.json")).json() as { version: string };
if (!version.startsWith("4.1.")) throw new Error(`tailwindcss ${version} in ${modules}; the fixtures are pinned to 4.1.x`);

for (const name of (await readdir(SOURCES)).filter((f) => f.endsWith(".html")).sort()) {
  const source = join(SOURCES, name);
  const html = await Bun.file(source).text();
  if (!html.includes(MARKER)) throw new Error(`${source} has no ${MARKER} marker`);
  const dir = await mkdtemp(join(tmpdir(), "markswift-tailwind-"));
  try {
    // Tailwind resolves `@import "tailwindcss"` relative to the input file.
    await symlink(modules, join(dir, "node_modules"), "dir");
    await Bun.write(join(dir, "input.css"), `@import "tailwindcss";\n@source "${source}";\n`);
    const run = Bun.spawn([cli, "-i", "input.css", "-o", "out.css"], { cwd: dir, stdout: "pipe", stderr: "pipe" });
    const [code, stderr] = await Promise.all([run.exited, new Response(run.stderr).text()]);
    if (code !== 0) throw new Error(`tailwindcss failed for ${name} (exit ${code}):\n${stderr}`);
    const css = await Bun.file(join(dir, "out.css")).text();
    const style = `<style>\n/* Generated by tests/conformance/tailwind-v4.ts from fixtures/_tailwind-v4/${name} with tailwindcss ${version}. Do not edit; regenerate. */\n${css}</style>`;
    const out = join(OUT, name);
    await Bun.write(out, html.replace(MARKER, () => style));
    console.log(out);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
