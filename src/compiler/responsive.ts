/** Compile two viewport captures into one width-selecting SwiftUI view. */
import { LayoutDoc } from "../model/layout.ts";
import type { FaceMetrics, BundledFamily } from "../model/fonts.ts";
import type { EmitMode } from "../swift/emit.ts";
import { RESPONSIVE_LAYOUT_RUNTIME } from "../swift/responsive-layout.ts";
import { compileLayouts, type CompileBatchResult } from "./batch.ts";
import { validateName } from "./naming.ts";

export interface ResponsiveCapture {
  layout: LayoutDoc;
  /** CSS viewport width used for this capture, which may differ from the captured root width. */
  viewportWidth: number;
}

export interface CompileResponsiveOptions {
  name: string;
  /** Inclusive upper width of the compact branch, in CSS points. */
  breakpoint: number;
  compact: ResponsiveCapture;
  regular: ResponsiveCapture;
  mode?: EmitMode;
  bundledFamilies?: Record<string, BundledFamily>;
  fontMetrics?: Record<string, FaceMetrics>;
  supportFiles?: Record<string, string>;
  assets?: Record<string, Uint8Array>;
}

/** Alias for callers that treat a responsive pair as one compiler input. */
export type CompileResponsiveInput = CompileResponsiveOptions;

export interface CompileResponsiveResult extends CompileBatchResult {
  name: string;
  /** Source of the public wrapper view, also present in files[`${name}.swift`]. */
  code: string;
}

export function compileResponsiveLayouts(options: CompileResponsiveInput): CompileResponsiveResult {
  validateName(options.name);
  const { breakpoint, compact, regular } = options;
  if (!Number.isSafeInteger(breakpoint) || breakpoint <= 0) throw new Error("breakpoint must be a positive integer");
  for (const [label, capture] of [["compact", compact], ["regular", regular]] as const) {
    if (!Number.isFinite(capture.viewportWidth) || capture.viewportWidth <= 0) {
      throw new Error(`${label}.viewportWidth must be a positive finite number`);
    }
  }
  if (!(compact.viewportWidth <= breakpoint && breakpoint < regular.viewportWidth)) {
    throw new Error("breakpoint must satisfy compact.viewportWidth <= breakpoint < regular.viewportWidth");
  }
  const compactDoc = LayoutDoc.parse(compact.layout);
  const regularDoc = LayoutDoc.parse(regular.layout);
  if (compactDoc.combo.theme !== regularDoc.combo.theme) throw new Error("responsive captures must use the same theme");

  const compactName = `${options.name}Compact`;
  const regularName = `${options.name}Regular`;
  validateName(compactName);
  validateName(regularName);
  const bundle = compileLayouts([
    {
      layout: compactDoc, name: compactName, componentId: `${options.name}-compact`,
      mode: options.mode, bundledFamilies: options.bundledFamilies, fontMetrics: options.fontMetrics,
      supportFiles: options.supportFiles, assets: options.assets,
    },
    {
      layout: regularDoc, name: regularName, componentId: `${options.name}-regular`,
      mode: options.mode, bundledFamilies: options.bundledFamilies, fontMetrics: options.fontMetrics,
    },
  ]);
  const wrapperName = `${options.name}.swift`;
  const runtimeName = "MarkswiftResponsiveLayout.swift";
  for (const path of [wrapperName, runtimeName]) rejectCollision(path, bundle);
  const code = wrapperSource(options.name, compactName, regularName, breakpoint);
  return {
    ...bundle, name: options.name, code,
    files: { ...bundle.files, [wrapperName]: code, [runtimeName]: RESPONSIVE_LAYOUT_RUNTIME },
  };
}

function rejectCollision(path: string, bundle: CompileBatchResult): void {
  const candidate = path.toLowerCase();
  for (const occupied of [...Object.keys(bundle.files), ...Object.keys(bundle.assets)]) {
    const other = occupied.toLowerCase();
    if (other === candidate || other.startsWith(`${candidate}/`) || candidate.startsWith(`${other}/`)) {
      throw new Error(`Responsive output path collision: ${path} and ${occupied}`);
    }
  }
}

function wrapperSource(name: string, compactName: string, regularName: string, breakpoint: number): string {
  return `// Generated by Markswift — do not edit. Responsive captures at one breakpoint.
import SwiftUI

struct ${name}: View {
    var body: some View {
        MarkswiftResponsiveLayout(breakpoint: ${breakpoint}) {
            ${compactName}()
        } regular: {
            ${regularName}()
        }
    }
}
`;
}
