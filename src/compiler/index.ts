import { validateName } from "./naming.ts";
/** Synchronous compiler. No browser, filesystem, Python or Apple toolchain required. */
import { LayoutDoc } from "../model/layout.ts";
import { inferScreen } from "../analysis/infer.ts";
import { emitSwift, SWIFT_RUNTIME, type EmitMode, type SwiftOutput } from "../swift/emit.ts";
import { extractTokens, emitDesignTokens, screenTokens } from "../swift/tokens.ts";
import type { FaceMetrics, BundledFamily } from "../model/fonts.ts";
import { GEOMETRY_RUNTIME } from "../swift/geometry-runtime.ts";
import { TEXT_OBSERVATION_RUNTIME } from "../swift/text-observation-runtime.ts";
import { TEXT_OBSERVED_GREEDY_RUNTIME } from "../swift/text-observed-greedy-runtime.ts";

export interface CompileOptions {
  /** Complete Swift type name, e.g. ProfileCard. ASCII identifiers starting with uppercase. */
  name?: string;
  mode?: EmitMode;
  bundledFamilies?: Record<string, BundledFamily>;
  fontMetrics?: Record<string, FaceMetrics>;
  /** Verification-only passive SwiftUI frame observations. Omitted by default. */
  geometryInstrumentation?: boolean;
  /** Verification-only source claims and passive TextRenderer observation; opt-in. */
  textInstrumentation?: boolean;
}

export interface CompileResult {
  name: string;
  code: string;
  /** All Swift sources needed by this view, including shared runtime helpers. */
  files: Record<string, string>;
  diagnostics: SwiftOutput["report"];
  /** Emitted semantic nodes by mapping confidence; does not measure visual fidelity. */
  mapping: SwiftOutput["mapping"];
  geometry?: SwiftOutput["geometry"];
  text?: SwiftOutput["text"];
}

/** Compile a captured layout. Custom fonts must be packaged by the caller and passed explicitly. */
export function compileLayout(layout: LayoutDoc, options: CompileOptions = {}): CompileResult {
  const name = options.name ?? "ConvertedView";
  validateName(name);
  const doc = LayoutDoc.parse(layout);
  const screen = inferScreen(doc, `${doc.combo.screen}-${doc.combo.theme}`, { bundledFamilies: options.bundledFamilies });
  const tokens = extractTokens([screen]);
  const result = emitSwift(screen, name, {
    mode: options.mode ?? "app", tokens: screenTokens(tokens, screen), fontMetrics: options.fontMetrics,
    geometryInstrumentation: options.geometryInstrumentation,
    textInstrumentation: options.textInstrumentation,
  });
  return {
    name, code: result.view, diagnostics: result.report, mapping: result.mapping,
    ...(result.geometry ? { geometry: result.geometry } : {}),
    ...(result.text ? { text: result.text } : {}),
    files: {
      [`${name}.swift`]: result.view,
      "MarkswiftRuntime.swift": SWIFT_RUNTIME,
      "MarkswiftTokens.swift": emitDesignTokens(tokens),
      "MarkswiftShapes.swift": "// Generated by Markswift — SVG paths as Shapes.\nimport SwiftUI\n\n" + Object.keys(result.shapes).sort().map((key) => result.shapes[key]).join("\n"),
      ...(result.geometry ? { "MarkswiftGeometry.swift": GEOMETRY_RUNTIME } : {}),
      ...(result.text ? { "MarkswiftTextObservation.swift": TEXT_OBSERVATION_RUNTIME + TEXT_OBSERVED_GREEDY_RUNTIME } : {}),
    },
  };
}

