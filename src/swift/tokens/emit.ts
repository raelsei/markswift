import type { TokenSet } from "./types.ts";
import { colorArgs } from "../format.ts";

const STATIC_HEADER = `// Generated by Markswift — colour tokens extracted from one captured theme.
//
// The generated view references these names instead of repeated Color.markswift(…) literals.
// Each token is exactly the literal it replaced; none adapts to the colour scheme.`;

const ADAPTIVE_HEADER = `// Generated by Markswift — colour tokens paired from the light and dark captures of one page.
//
// The generated view references these names instead of inline Color.markswift(…) literals.
// An adaptive token is Color(light:dark:) and follows the colour scheme; a static token is the
// same colour in both themes.`;

/** `Color(light:dark:)` — one token, resolved from the trait collection at draw time. */
const TOKENS_SUPPORT = `extension Color {
    /// Light/dark pair as one colour, resolved per \`UITraitCollection.userInterfaceStyle\`:
    /// it follows the system appearance, \`.preferredColorScheme\` on a hosted window, and
    /// \`\\.colorScheme\` in the environment (which is how the render harness sets the theme).
    nonisolated init(light: Color, dark: Color) {
        let l = UIColor(light), d = UIColor(dark)
        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? d : l })
    }
}`;

/**
 * `MarkswiftTokens.swift`: the `Color(light:dark:)` initialiser plus one `static let` per token.
 * Static tokens emit a single colour; semantic tokens emit the pair. `adaptive` says whether the
 * set was paired from a light and a dark capture, which the header states.
 */
export function emitDesignTokens(set: TokenSet, adaptive = false): string {
  const semantic = set.tokens.filter((t) => t.kind === "semantic");
  const slots = set.tokens.reduce((n, t) => n + t.slots, 0);
  const out: string[] = [
    adaptive ? ADAPTIVE_HEADER : STATIC_HEADER,
    `//`,
    adaptive
      ? `// ${set.tokens.length} tokens: ${semantic.length} adaptive (light/dark pairs), ${set.tokens.length - semantic.length} static.`
      : `// ${set.tokens.length} tokens, all static.`,
    `// ${slots} colour slots carry them; ${set.inlineSlots} single-use colours${adaptive ? " identical in both themes" : ""} stay inline.`,
    `import SwiftUI`,
    `import UIKit`,
    ``,
    TOKENS_SUPPORT,
    ``,
    `extension Color {`,
  ];
  for (const t of set.tokens) {
    const where = t.uses.length === 1 ? `1 use` : `${t.uses.length} uses`;
    out.push(`    /// ${t.role} · ${where}${t.hint ? ` · --${t.hint}` : ""}`);
    out.push(
      t.kind === "semantic"
        ? `    static let ${t.name} = Color(light: .markswift(${colorArgs(t.light)}), dark: .markswift(${colorArgs(t.dark)}))`
        : `    static let ${t.name} = Color.markswift(${colorArgs(t.light)})`,
    );
  }
  out.push(`}`);
  return out.join("\n") + "\n";
}
