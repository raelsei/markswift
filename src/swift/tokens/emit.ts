import type { Color } from "../../css/index.ts";
import type { TokenSet, TokenRole } from "./types.ts";
import { colorArgs } from "../format.ts";
// ---------- emission ----------

const TOKENS_HEADER = `// Generated by Markswift — design tokens extracted from the light/dark pair of the run.
//
// The generated views reference these names instead of inline Color.markswift(…) literals, so one
// screen's view carries both themes. A token resolves to exactly the literal it replaced:
// measured under ImageRenderer on the simulator, token and literal render the same pixels.`;

/** `Color(light:dark:)` — one token, resolved from the trait collection at draw time. */
const TOKENS_SUPPORT = `extension Color {
    /// Light/dark pair as one colour, resolved per \`UITraitCollection.userInterfaceStyle\`:
    /// it follows the system appearance, \`.preferredColorScheme\` on a hosted window, and
    /// \`\\.colorScheme\` in the environment (which is how the render harness sets the theme).
    nonisolated init(light: Color, dark: Color) {
        let l = UIColor(light), d = UIColor(dark)
        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? d : l })
    }
}`;

/**
 * `MarkswiftTokens.swift`: the `Color(light:dark:)` initialiser plus one `static let` per token.
 * Static tokens emit a single colour; semantic tokens emit the pair.
 */
export function emitDesignTokens(set: TokenSet): string {
  const semantic = set.tokens.filter((t) => t.kind === "semantic");
  const out: string[] = [
    TOKENS_HEADER,
    `//`,
    `// ${set.tokens.length} tokens: ${semantic.length} semantic (light/dark pairs), ${set.tokens.length - semantic.length} static.`,
    `// ${set.replaceableLiterals} colour slots across the run carry them; ${set.inlineSlots} single-use colours stay inline.`,
    `import SwiftUI`,
    `import UIKit`,
    ``,
    TOKENS_SUPPORT,
    ``,
    `extension Color {`,
  ];
  for (const t of set.tokens) {
    const where = t.uses.length === 1 ? `1 use` : `${t.uses.length} uses`;
    out.push(`    /// ${t.role} · ${where}${t.hint ? ` · --${t.hint}` : ""}`);
    out.push(
      t.kind === "semantic"
        ? `    static let ${t.name} = Color(light: .markswift(${colorArgs(t.light)}), dark: .markswift(${colorArgs(t.dark)}))`
        : `    static let ${t.name} = Color.markswift(${colorArgs(t.light)})`,
    );
  }
  out.push(`}`);
  return out.join("\n") + "\n";
}

/** `tokens.json` payload: `name → { light, dark, uses }`, plus the counts the header reports. */
export function tokensJson(set: TokenSet): string {
  const tokens: Record<string, { kind: string; light: Color; dark: Color; hint?: string; role: TokenRole; uses: string[] }> = {};
  for (const t of set.tokens) {
    tokens[t.name] = { kind: t.kind, light: t.light, dark: t.dark, ...(t.hint ? { hint: t.hint } : {}), role: t.role, uses: t.uses };
  }
  const semantic = set.tokens.filter((t) => t.kind === "semantic").length;
  return JSON.stringify(
    { counts: { total: set.tokens.length, semantic, static: set.tokens.length - semantic, replaceableLiterals: set.replaceableLiterals, inlineSlots: set.inlineSlots }, tokens },
    null,
    1,
  ) + "\n";
}
