import core from "./runtime/core.swift" with { type: "text" };
import controls from "./runtime/controls.swift" with { type: "text" };
import measuredLayout from "./runtime/measured-layout.swift" with { type: "text" };
import flow from "./runtime/flow.swift" with { type: "text" };
import tracks from "./runtime/tracks.swift" with { type: "text" };
import flexRow from "./runtime/flex-row.swift" with { type: "text" };
import bands from "./runtime/bands.swift" with { type: "text" };
import { GENERATED_BY } from "../model/version.ts";

/**
 * `MarkswiftRuntime.swift`. `controls.swift` opens with `import UniformTypeIdentifiers`, which
 * Swift accepts anywhere at file scope, so every part is appended at top level. `core.swift` keeps a
 * version-free header; the shipped runtime names the version that generated it.
 */
export const SWIFT_RUNTIME =
  core.replace(/^\/\/ Generated by Markswift —/, `// ${GENERATED_BY} —`) +
  "\n" +
  [controls, measuredLayout, flow, tracks, flexRow, bands].join("\n\n");
