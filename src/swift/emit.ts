/** Assemble a screen from cohesive Swift emission modules. */
import type { Screen, SemNode, StackNode, GridNode } from "../model/semantic.ts";
import { Writer, colorArgs, num } from "./format.ts";
import { controlMembers } from "./control-state.ts";
import type { EmitContext, EmitOptions, NodeMapping, SwiftOutput } from "./context.ts";
import { refOf } from "./nodes.ts";
import { containerExpr } from "./layout.ts";
import { visit } from "./traversal.ts";
import { geometryInstrumentation } from "./geometry-observation.ts";
export type { EmitMode, EmitOptions, SwiftOutput } from "./context.ts";
export { SWIFT_RUNTIME } from "./runtime.ts";
export function emitSwift(screen: Screen, viewName: string, opts: EmitOptions): SwiftOutput {
  const shapes: Record<string, string> = {};
  const report: SwiftOutput["report"] = [];
  const mapping: NodeMapping = { total: 0, mapped: 0, approximated: 0, unmapped: 0 };
  const props: Array<{ name: string; node: SemNode }> = [];
  const seen: Record<string, number> = {};

  // Collect container properties depth-first so the body reads top-down.
  // Repeated template ids (sc-for iterations) get an occurrence suffix.
  visit(screen.root, (n) => {
    if (n.kind !== "stack" && n.kind !== "grid") return;
    const base = propName(n.id, props.length);
    const k = (seen[base] = (seen[base] ?? 0) + 1);
    props.push({ name: k === 1 ? base : `${base}_r${k}`, node: n });
  });
  const nameOf = new Map<SemNode, string>();
  for (const p of props) nameOf.set(p.node, p.name);
  // Control state pass: a control owns its value, so the view that holds it declares the storage.
  const control = controlMembers(screen.root, opts.mode);
  const geometry = opts.geometryInstrumentation ? geometryInstrumentation(screen.root, viewName) : undefined;
  const ctx: EmitContext = { fontMetrics: opts.fontMetrics ?? {}, nameOf, shapes, screen, mode: opts.mode, control, tokens: opts.tokens, geometry, renderNode: (node) => refOf(node, ctx) };

  const w = new Writer();
  const comment = (value: string) => value.replace(/[\r\n\u2028\u2029]/g, " ");
  w.line("// Generated by Markswift — do not edit. Source: " + comment(screen.source) + " (" + comment(screen.name) + ", " + screen.theme + ")");
  w.line("import SwiftUI");
  w.line();
  w.block(`struct ${viewName}: View {`, () => {
    for (const d of control.decls) w.line(d);
    if (control.decls.length) w.line();
    w.block("var body: some View {", () => {
      w.line(refOf(screen.root, ctx));
    });
    for (const p of props) {
      w.line();
      w.line(`// ${comment(p.node.id)}`);
      w.block(`private var ${p.name}: some View {`, () => {
        for (const l of containerExpr(p.node as StackNode | GridNode, ctx)) w.line(l);
      });
    }
  });
  w.line();
  w.block(`#Preview("${viewName}") {`, () => {
    w.line(`${viewName}()`);
    w.line(`.frame(width: ${num(screen.size.w)}, height: ${num(screen.size.h)})`);
    w.line(`.background(Color.markswift(${colorArgs(screen.theme === "dark" ? { r: 0.043, g: 0.055, b: 0.075, a: 1 } : { r: 0.957, g: 0.965, b: 0.98, a: 1 })}))`);
    w.line(`.preferredColorScheme(.${screen.theme})`);
  });
  // After emission: `note()` may have downgraded nodes for emit-time approximations.
  visit(screen.root, (n) => {
    mapping.total++;
    mapping[n.confidence]++;
    if (n.confidence !== "mapped") report.push({ id: n.id, kind: n.kind, confidence: n.confidence, notes: n.notes });
  });
  return { view: w.toString(), shapes, report, mapping, ...(geometry ? { geometry: geometry.manifest } : {}) };
}

function propName(id: string, i: number): string {
  const clean = id.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  return `v_${clean || "n" + i}`;
}
